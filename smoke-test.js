const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const server = read('server.js');
const html = read('public/index.html');
const script = read('google-apps-script.gs');
const env = read('.env.example');
const render = read('render.yaml');
const seed = JSON.parse(read('seed.json'));

assert.match(server, /app\.post\('\/api\/login'/, 'server has admin login endpoint');
assert.match(server, /app\.put\('\/api\/state'/, 'server has protected state update endpoint');
assert.match(server, /app\.get\('\/api\/google-sheets\/status'/, 'Google Sheets status endpoint exists');
assert.match(server, /app\.post\('\/api\/google-sheets\/sync'/, 'manual Google Sheets sync endpoint exists');
assert.match(server, /setInterval\(\(\)=>\{if\(googleSheetsConfigured\(\)\)syncGoogleSheets/, 'server polls Google Sheets');
assert.match(html, /id="track-bg"/, 'animated track canvas exists');
assert.match(html, /id="mobile-nav"/, 'mobile navigation exists');
assert.match(html, /Google Sheets status/, 'admin UI exposes Google Sheets status');
assert.match(html, /admin-stats/, 'admin console has refreshed dashboard styling');
assert.match(html, /function syncGoogleSheets\(/, 'admin UI exposes manual sync');
assert.match(html, /name=\"p\" type=\"password\"/, 'admin login requires only a password');
assert.doesNotMatch(html, /Backend API URL|Test backend connection/, 'login has no confusing backend URL controls');
assert.match(html, /apiFetch\('\/api\/login'/, 'login connects to the backend (same-origin by default)');
assert.match(html, /loadServerState\(true\)/, 'login fails clearly if backend state cannot be loaded');
assert.match(script, /function doGet\(/, 'Apps Script pull endpoint exists');
assert.match(script, /function doPost\(/, 'Apps Script push endpoint exists');
assert.match(script, /function onEdit\(/, 'manual spreadsheet edits are timestamped');
assert.match(script, /State Backup/, 'complete website state is preserved outside visible tab schemas');
assert.match(script, /Leadership Role.*Course Length.*Graduated.*Photo URL.*Achievements JSON/, 'athlete-specific fields are represented in the sheet schema');
assert.match(script, /Image URL \(optional\)/, 'gallery image links are represented in the sheet schema');
assert.match(server, /googleSheetsRequest\('POST',\{action:'read'\}\)/, 'sync reads sheet data without putting the shared token in a URL');
assert.match(script, /SYNC_TOKEN/, 'Apps Script protects requests with shared token');
assert.equal(env.match(/^ADMIN_PASSWORD=iitbhu11$/m)?.[0], 'ADMIN_PASSWORD=iitbhu11', 'requested local admin password is configured');
assert.match(render, /key: ADMIN_PASSWORD\s+value: iitbhu11/, 'Render blueprint uses requested admin password');
assert.ok(seed.site && Array.isArray(seed.ath) && Array.isArray(seed.med) && Array.isArray(seed.evt), 'seed includes core website data');
console.log('PASS: static smoke checks for password-only admin login, same-origin backend, website state, track/mobile UI, Google Sheets bridge, deployment config and seed data.');
console.log('NOTE: These checks do not replace a live Google Apps Script/Render integration test.');
